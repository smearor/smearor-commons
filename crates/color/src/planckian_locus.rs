#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn t6500_sits_near_d65() {
        let Some((_, x, y)) = PLANCKIAN_LOCUS.iter().find(|(k, _, _)| *k == 6500) else {
            panic!("6500K missing");
        };
        assert!((*x - 0.3135).abs() < 0.005 && (*y - 0.3237).abs() < 0.005);
    }

    #[test]
    fn the_locus_moves_from_red_to_blue() {
        let (first, last) = (PLANCKIAN_LOCUS.first(), PLANCKIAN_LOCUS.last());
        assert!(matches!((first, last), (Some(f), Some(l)) if f.1 > l.1 && f.2 > l.2));
    }
}
