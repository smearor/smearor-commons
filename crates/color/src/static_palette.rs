use crate::Color;
use crate::Palette;
use crate::PaletteDefinition;
use serde::Serialize;
use serde::Serializer;
use serde::ser::SerializeMap;
use std::borrow::Borrow;
use std::hash::Hash;

/// A `const`-constructible [`Palette`] alternative: name/color pairs
/// stored in a `&'static` slice and looked up by linear scan.
///
/// [`Palette`] itself can never be built in `const` contexts - its
/// `HashMap` needs a runtime-seeded `RandomState`. For static theme
/// tables (a handful of colors per theme) the linear scan of
/// `StaticPalette` is as fast as hashing, needs no allocation and is
/// fully `const`-evaluable. Convert into the hash-backed `Palette`
/// via [`Palette::from`] when lookup volume justifies it.
///
/// ```
/// use smearor_commons_color::Color;
/// use smearor_commons_color::StaticPalette;
/// use smearor_commons_color::palette_definition;
/// use smearor_commons_color::static_palette;
///
/// palette_definition! {
///     /// Square colors of a board theme.
///     pub enum BoardSlot {
///         /// Light squares.
///         Light => "light",
///         /// Dark squares.
///         Dark => "dark"
///     }
/// }
///
/// static BOARD: StaticPalette<BoardSlot, u8> = static_palette! {
///     BoardSlot::Light => Color::<u8>::new(0xED, 0xD4, 0x9E),
///     BoardSlot::Dark => Color::<u8>::new(0x73, 0x4D, 0x2E),
/// };
/// assert_eq!(BOARD.get(&BoardSlot::Light), Some(&Color::<u8>::new(0xED, 0xD4, 0x9E)));
/// ```
/// Since the entries live in `&'static` storage, keys must be
/// `const`-evaluable and drop-free - fieldless enums generated by
/// [`crate::palette_definition!`], `&'static str` or integers.
/// [`crate::NamedColor`] cannot be used here: its `Cow` name has a
/// destructor, which prevents static promotion.
#[derive(Debug, PartialEq, Eq)]
pub struct StaticPalette<N: 'static, T: 'static> {
    /// Name/color pairs in declaration order.
    entries: &'static [(N, Color<T>)],
}

// The slice reference is `Copy` regardless of `N`/`T` - manual impls
// avoid the bounds a `derive` would add.
impl<N: 'static, T: 'static> Copy for StaticPalette<N, T> {}

impl<N: 'static, T: 'static> Clone for StaticPalette<N, T> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<N: 'static, T: 'static> StaticPalette<N, T> {
    /// Creates a palette from `&'static` name/color pairs -
    /// `const`-usable.
    pub const fn new(entries: &'static [(N, Color<T>)]) -> Self {
        Self { entries }
    }

    /// The number of colors - `const`-usable.
    pub const fn len(&self) -> usize {
        self.entries.len()
    }

    /// `true` when the palette holds no colors - `const`-usable.
    pub const fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// The name/color pairs in declaration order - `const`-usable.
    pub const fn entries(&self) -> &'static [(N, Color<T>)] {
        self.entries
    }

    /// Iterates `(name, color)` pairs in declaration order.
    pub fn iter(&self) -> impl Iterator<Item = (&N, &Color<T>)> {
        self.entries.iter().map(|(name, color)| (name, color))
    }

    /// The color registered under `name` - linear scan in
    /// declaration order.
    pub fn get<Q>(&self, name: &Q) -> Option<&Color<T>>
    where
        N: Borrow<Q>,
        Q: PartialEq + ?Sized,
    {
        self.entries.iter().find(|(n, _)| n.borrow() == name).map(|(_, color)| color)
    }

    /// `true` when a color is registered under `name`.
    pub fn contains<Q>(&self, name: &Q) -> bool
    where
        N: Borrow<Q>,
        Q: PartialEq + ?Sized,
    {
        self.entries.iter().any(|(n, _)| n.borrow() == name)
    }

    /// The color registered under `name`, or `fallback` when absent.
    pub fn get_or<Q>(&self, name: &Q, fallback: Color<T>) -> Color<T>
    where
        N: Borrow<Q>,
        Q: PartialEq + ?Sized,
        T: Clone,
    {
        self.get(name).cloned().unwrap_or(fallback)
    }
}

/// Methods available when the key type enumerates its vocabulary.
impl<N: PaletteDefinition, T: 'static> StaticPalette<N, T> {
    /// The declared slots that have no color registered, in
    /// declaration order.
    pub fn missing(&self) -> Vec<N> {
        N::slots().iter().filter(|slot| !self.contains(*slot)).copied().collect()
    }

    /// `true` when every declared slot carries a color.
    pub fn is_complete(&self) -> bool {
        N::slots().iter().all(|slot| self.contains(slot))
    }
}

/// An empty palette.
impl<N: 'static, T: 'static> Default for StaticPalette<N, T> {
    fn default() -> Self {
        Self::new(&[])
    }
}

impl<'a, N: 'static, T: 'static> IntoIterator for &'a StaticPalette<N, T> {
    type Item = &'a (N, Color<T>);
    type IntoIter = std::slice::Iter<'a, (N, Color<T>)>;

    fn into_iter(self) -> Self::IntoIter {
        self.entries.iter()
    }
}

/// Upgrading clones the pairs into a hash-backed [`Palette`].
impl<N: 'static, T: 'static> From<StaticPalette<N, T>> for Palette<N, T>
where
    N: Clone + Eq + Hash,
    T: Clone,
{
    fn from(palette: StaticPalette<N, T>) -> Self {
        palette.entries.iter().cloned().collect()
    }
}

/// Same wire format as [`Palette`]: a map `{ "name": "#rrggbb(aa)" }`
/// in declaration order. Deserialization is only implemented for
/// `Palette` - convert via [`Palette::from`].
impl<N: 'static, T: 'static> Serialize for StaticPalette<N, T>
where
    N: Serialize,
    Color<T>: Serialize,
{
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        let mut map = serializer.serialize_map(Some(self.entries.len()))?;
        for (name, color) in self.entries {
            map.serialize_entry(name, color)?;
        }
        map.end()
    }
}

/// Builds a [`StaticPalette`] from `name => color` pairs - the
/// generated expression is `const`-evaluable and usable in `const`
/// and `static` contexts. All values must be const expressions
/// (`Color::<u8>::new(0xED, 0xD4, 0x9E)` or
/// `Color::<u8>::from_rgb_u32(0xEDD49E)`) and names must already
/// have the key type (`BoardSlot::Light`,
/// `NamedColor::new("light")`) - no `Into` conversion happens in
/// const contexts.
///
/// ```
/// use smearor_commons_color::Color;
/// use smearor_commons_color::StaticPalette;
/// use smearor_commons_color::static_palette;
///
/// const GRAYSCALE: StaticPalette<&'static str, u8> = static_palette! {
///     "light" => Color::<u8>::from_rgb_u32(0xEDD49E),
///     "dark" => Color::<u8>::from_rgb_u32(0x734D2E),
/// };
/// assert_eq!(GRAYSCALE.len(), 2);
/// ```
#[macro_export]
macro_rules! static_palette {
    ($($name:expr => $color:expr),* $(,)?) => {
        $crate::StaticPalette::new(&[$(($name, $color)),*])
    };
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::palette_definition;

    palette_definition! {
        /// Colors of a chess board theme.
        pub enum BoardSlot {
            /// Light squares.
            Light => "light",
            /// Dark squares.
            Dark => "dark",
            /// Frame around the board.
            Frame => "frame"
        }
    }

    const BOARD: StaticPalette<BoardSlot, u8> = static_palette! {
        BoardSlot::Light => Color::<u8>::from_rgb_u32(0xEDD49E),
        BoardSlot::Dark => Color::<u8>::from_rgb_u32(0x734D2E),
    };

    const STRINGS: StaticPalette<&'static str, u8> = static_palette! {
        "light" => Color::<u8>::from_rgb_u32(0xEDD49E),
        "dark" => Color::<u8>::from_rgb_u32(0x734D2E),
    };

    #[test]
    fn const_palette_lookup_by_enum_key() {
        assert_eq!(BOARD.get(&BoardSlot::Light), Some(&Color::<u8>::new(0xED, 0xD4, 0x9E)));
        assert!(BOARD.contains(&BoardSlot::Dark));
        assert_eq!(BOARD.get(&BoardSlot::Frame), None);
        assert_eq!(BOARD.len(), 2);
        assert!(!BOARD.is_empty());
    }

    #[test]
    fn const_palette_lookup_str_keys() {
        assert_eq!(STRINGS.get("light"), Some(&Color::<u8>::new(0xED, 0xD4, 0x9E)));
        assert_eq!(STRINGS.get_or("frame", Color::<u8>::BLACK), Color::<u8>::BLACK);
    }

    #[test]
    fn missing_reports_unfilled_slots() {
        assert_eq!(BOARD.missing(), vec![BoardSlot::Frame]);
        assert!(!BOARD.is_complete());
        let full = StaticPalette::new(&[
            (BoardSlot::Light, Color::<u8>::BLACK),
            (BoardSlot::Dark, Color::<u8>::BLACK),
            (BoardSlot::Frame, Color::<u8>::BLACK),
        ]);
        assert!(full.is_complete());
        assert!(full.missing().is_empty());
    }

    #[test]
    fn iter_keeps_declaration_order() {
        let names: Vec<BoardSlot> = BOARD.iter().map(|(name, _)| *name).collect();
        assert_eq!(names, vec![BoardSlot::Light, BoardSlot::Dark]);
    }

    #[test]
    fn into_palette_clones_into_hashmap() {
        let palette = Palette::from(BOARD);
        assert_eq!(palette.get(&BoardSlot::Light), Some(&Color::<u8>::new(0xED, 0xD4, 0x9E)));
        assert_eq!(palette.len(), 2);
        assert_eq!(palette.missing(), vec![BoardSlot::Frame]);
    }

    #[test]
    fn serialize_matches_palette_wire_format() {
        let json = serde_json::to_string(&BOARD).unwrap();
        assert_eq!(json, "{\"Light\":\"#edd49e\",\"Dark\":\"#734d2e\"}");
    }
}
