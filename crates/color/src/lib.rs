//! Generic color types for the Smearor ecosystem.
//!
//! Channel-generic [`Color<T>`] (normalized `f64`/`f32` and byte `u8`),
//! parsing via `FromStr`/`Display` and consolidated color operations.
//! Textual representations have dedicated types: [`HexColor`] validates
//! `#`-prefixed hex strings; [`CssNamedColor`], [`PantoneNamedColor`]
//! and [`PantoneFhiNamedColor`] enumerate the CSS Color Level 4,
//! Pantone Matching System and Pantone FHI color vocabularies.
//! [`Palette<N, T>`] maps semantic color names
//! to colors: keys are either a [`PaletteDefinition`] enum (type-safe
//! vocabulary, generated by [`palette_definition!`]) or the dynamic
//! [`NamedColor`]. `gtk4`/`cairo` conversions live behind feature gates.
//!
//! Semantic color types (`FigureColor`, `LineColor`, `PawnColor`, ...)
//! stay in consumer crates as thin newtype wrappers around [`Color<T>`].

